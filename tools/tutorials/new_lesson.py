def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--number", type=int, required=True)
    ap.add_argument("--slug", required=True, help="kebab-case slug without the number")
    ap.add_argument("--h1", required=True)
    ap.add_argument("--keyword", required=True)
    ap.add_argument("--block", required=True)
    ap.add_argument("--version", default="0.22.0")
    ap.add_argument("--out", default="lessons")
    a = ap.parse_args(argv)

    stem = f"{a.number:02d}-{a.slug}"
    folder = pathlib.Path(a.out) / stem
    if folder.exists():
        print(f"{folder} already exists, nothing written", file=sys.stderr)
        return 1
    (folder / "images").mkdir(parents=True)
    (folder / "data").mkdir()
    fields = dict(number=a.number, slug=a.slug, h1=a.h1, keyword=a.keyword, block=a.block,
                  version=a.version, today=dt.date.today().isoformat())
    (folder / f"{stem}.md").write_text(LESSON.format(**fields), encoding="utf-8")
    (folder / f"{stem}.evidence.md").write_text(EVIDENCE.format(**fields), encoding="utf-8")
    (folder / "captures.json").write_text(json.dumps(CAPTURES, indent=2), encoding="utf-8")
    (folder / "prepare.py").write_text(PREPARE.format(**fields), encoding="utf-8")
    shutil.copy(HERE / "datagen.py", folder / "datagen.py")
    print(f"created {folder}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
